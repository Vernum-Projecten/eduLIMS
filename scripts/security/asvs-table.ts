// Keeps the ASVS 5.0 applicability table (docs/security/asvs-5.0-applicability.md) in step
// with the vendored requirement list. Run on Node's type stripping:
//
//   node scripts/security/asvs-table.ts           # rewrite the table, keeping every judgement
//   node scripts/security/asvs-table.ts --check   # exit 1 when the table and the list disagree
//
// The rewrite adds a row with TODO cells for an id the table lacks, drops a row whose id the
// vendored list no longer has, and recounts the summary; the hand-written cells stay.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const SOURCE =
  "docs/security/vendor/asvs/docs_en/OWASP_Application_Security_Verification_Standard_5.0.0_en.flat.json";
/** `ASVS_TABLE` points the script at a copy, for the self-test of scripts/checks/asvs-coverage.sh. */
const TABLE = process.env["ASVS_TABLE"] ?? "docs/security/asvs-5.0-applicability.md";
const BEGIN = "<!-- asvs-table:begin (generated by scripts/security/asvs-table.ts) -->";
const END = "<!-- asvs-table:end -->";
const TODO = "TODO";

const APPLIES = ["yes", "partly", "no"] as const;
const STATUSES = ["met", "partial", "planned", "open", "n-a"] as const;

/** One requirement as the vendored flat JSON lists it. */
interface Requirement {
  chapter_id: string;
  chapter_name: string;
  section_id: string;
  section_name: string;
  req_id: string;
  L: string;
}

/** The hand-written columns of one table row. */
interface Judgement {
  applies: string;
  where: string;
  verification: string;
  status: string;
}

const ROW = /^\| (V\d+\.\d+\.\d+) \| (\d) \|(.*)\|$/;

function readRequirements(): Requirement[] {
  const parsed: unknown = JSON.parse(readFileSync(join(REPO, SOURCE), "utf8"));
  if (typeof parsed !== "object" || parsed === null || !("requirements" in parsed)) {
    throw new Error(`${SOURCE}: no "requirements" array`);
  }
  const list = parsed.requirements;
  if (!Array.isArray(list)) throw new Error(`${SOURCE}: "requirements" is not an array`);
  return list.map((item: Requirement) => item);
}

/** Returns the vendored chapter file of a chapter id (`V11` is `en/0x20-V11-….md`). */
function chapterFile(chapterId: string): string {
  const index = Number(chapterId.slice(1)) - 1;
  const prefix = `0x${1 + Math.floor(index / 10)}${index % 10}-${chapterId}-`;
  const match = readdirSync(join(REPO, "docs/security/vendor/asvs/en")).find((name) =>
    name.startsWith(prefix),
  );
  if (match === undefined) throw new Error(`no vendored chapter file for ${chapterId}`);
  return `vendor/asvs/en/${match}`;
}

function parseJudgements(text: string): { judgements: Map<string, Judgement>; ids: string[] } {
  const judgements = new Map<string, Judgement>();
  const ids: string[] = [];
  for (const line of text.split("\n")) {
    const match = ROW.exec(line);
    if (!match) continue;
    const id = match[1] ?? "";
    const cells = (match[3] ?? "").split("|").map((cell) => cell.trim());
    if (cells.length !== 4)
      throw new Error(`${TABLE}: ${id} has ${cells.length + 2} columns, not 6`);
    const [applies = TODO, where = TODO, verification = TODO, status = TODO] = cells;
    ids.push(id);
    judgements.set(id, { applies, where, verification, status });
  }
  return { judgements, ids };
}

function render(requirements: Requirement[], judgements: Map<string, Judgement>): string {
  const out: string[] = [BEGIN, ""];
  const rows = requirements.map((req) => ({
    req,
    judgement: judgements.get(req.req_id) ?? {
      applies: TODO,
      where: TODO,
      verification: TODO,
      status: TODO,
    },
  }));

  const count = (pick: (j: Judgement, r: Requirement) => boolean) =>
    rows.filter(({ req, judgement }) => pick(judgement, req)).length;
  out.push("| Count | Requirements |", "|---|---|");
  out.push(`| All ASVS 5.0.0 requirements | ${rows.length} |`);
  out.push(`| Level 1 and 2 (the target) | ${count((_, r) => r.L !== "3")} |`);
  out.push(`| Applicable (yes or partly) | ${count((j) => j.applies !== "no")} |`);
  for (const status of STATUSES) {
    out.push(`| Status ${status} | ${count((j) => j.status === status)} |`);
  }
  out.push("");

  let chapter = "";
  let section = "";
  for (const { req, judgement } of rows) {
    if (req.chapter_id !== chapter) {
      if (chapter !== "") out.push("");
      chapter = req.chapter_id;
      section = "";
      out.push(`### ${req.chapter_id} ${req.chapter_name}`, "");
      out.push(`Text: [${chapterFile(req.chapter_id)}](${chapterFile(req.chapter_id)}).`, "");
    }
    if (req.section_id !== section) {
      if (section !== "") out.push("");
      section = req.section_id;
      out.push(`#### ${req.section_id} ${req.section_name}`, "");
      out.push("| ID | L | Applies | Where | Verification | Status |", "|---|---|---|---|---|---|");
    }
    const { applies, where, verification, status } = judgement;
    out.push(`| ${req.req_id} | ${req.L} | ${applies} | ${where} | ${verification} | ${status} |`);
  }
  out.push("", END);
  return out.join("\n");
}

function problemsOf(
  requirements: Requirement[],
  ids: string[],
  judgements: Map<string, Judgement>,
) {
  const problems: string[] = [];
  const known = new Set(requirements.map((req) => req.req_id));
  const seen = new Set<string>();
  for (const id of ids) {
    if (!known.has(id))
      problems.push(`${id} is in the table, and the vendored ASVS has no such id`);
    if (seen.has(id)) problems.push(`${id} is in the table twice`);
    seen.add(id);
  }
  for (const req of requirements) {
    const judgement = judgements.get(req.req_id);
    if (judgement === undefined) {
      problems.push(`${req.req_id} is missing from the table`);
      continue;
    }
    const { applies, where, verification, status } = judgement;
    if ([applies, where, verification, status].includes(TODO)) {
      problems.push(`${req.req_id} still has a TODO cell`);
    }
    if (!(APPLIES as readonly string[]).includes(applies)) {
      problems.push(`${req.req_id}: applies is "${applies}", not one of ${APPLIES.join(", ")}`);
    }
    if (!(STATUSES as readonly string[]).includes(status)) {
      problems.push(`${req.req_id}: status is "${status}", not one of ${STATUSES.join(", ")}`);
    }
    if ((applies === "no") !== (status === "n-a")) {
      problems.push(`${req.req_id}: applies "${applies}" and status "${status}" disagree`);
    }
  }
  return problems;
}

function main(): void {
  const check = process.argv.includes("--check");
  const requirements = readRequirements();
  const path = resolve(REPO, TABLE);
  const text = readFileSync(path, "utf8");
  const begin = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (begin < 0 || end < begin)
    throw new Error(`${TABLE}: no generated region (${BEGIN} … ${END})`);
  const { judgements, ids } = parseJudgements(text.slice(begin, end));
  const updated = `${text.slice(0, begin)}${render(requirements, judgements)}${text.slice(end + END.length)}`;

  if (!check) {
    writeFileSync(path, updated);
    process.stdout.write(`asvs-table: ${requirements.length} requirements in ${TABLE}\n`);
    return;
  }
  const problems = problemsOf(requirements, ids, judgements);
  if (updated !== text) {
    problems.push(
      `${TABLE} is out of step with the vendored list; run node scripts/security/asvs-table.ts`,
    );
  }
  if (problems.length > 0) {
    process.stderr.write(`asvs-table: ${problems.length} problems\n  ${problems.join("\n  ")}\n`);
    process.exit(1);
  }
  process.stdout.write(`asvs-table: all ${requirements.length} ASVS 5.0.0 ids are judged once\n`);
}

main();
