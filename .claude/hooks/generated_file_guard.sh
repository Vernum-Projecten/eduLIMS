# Claude Code PreToolUse hook (matcher: Edit|Write).
# Blocks a hand edit of a file a tool owns:
#   - src/routeTree.gen.ts: the TanStack Router plugin writes it on
#     `pnpm dev` and `pnpm build` (.claude/rules/tanstack.md)
#   - pnpm-lock.yaml: pnpm writes it (`pnpm install`, `pnpm add`)
#   - *.gen.ts under src/server/db/: `pnpm db:generate-types` writes the
#     Kysely types (.claude/rules/database.md)
#   - the library skills pnpm links into .claude/skills/ (symlinks into
#     node_modules; .claude/skills/.gitignore lists them)
#
# Reads the tool-call JSON on stdin. Exit 2 blocks; exit 0 allows.

set -euo pipefail

payload="$(cat)"

if command -v jq >/dev/null 2>&1; then
  file="$(printf '%s' "$payload" | jq -r '.tool_input.file_path // empty' 2>/dev/null || true)"
else
  file="$(printf '%s' "$payload" | sed -n 's/.*"file_path"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n 1)"
fi
[[ -n "${file:-}" ]] || exit 0

root="${CLAUDE_PROJECT_DIR:-$(pwd)}"
rel="${file#"$root"/}"

case "$rel" in
src/routeTree.gen.ts | */src/routeTree.gen.ts)
  echo "BLOCKED: src/routeTree.gen.ts is generated by the TanStack Router plugin. Add or change a file under src/routes/ and run 'pnpm dev' or 'pnpm build' to regenerate it." >&2
  exit 2
  ;;
pnpm-lock.yaml | */pnpm-lock.yaml)
  echo "BLOCKED: pnpm-lock.yaml is written by pnpm. Change package.json with 'pnpm add <pkg>@<exact-version>' or run 'pnpm install'." >&2
  exit 2
  ;;
src/server/db/*.gen.ts | */src/server/db/*.gen.ts)
  echo "BLOCKED: $rel is generated from the database schema. Write a migration and run 'pnpm db:migrate' then 'pnpm db:generate-types' (/db-migration)." >&2
  exit 2
  ;;
*) ;;
esac

# A path under .claude/skills/ that resolves into node_modules is a library
# skill pnpm links; edits belong upstream.
case "$rel" in
.claude/skills/* | */.claude/skills/*)
  skill_dir="$root/.claude/skills/$(printf '%s' "${rel#*.claude/skills/}" | cut -d/ -f1)"
  if [[ -L "$skill_dir" ]]; then
    echo "BLOCKED: $skill_dir is a library skill that pnpm links from node_modules. Do not edit it; write a project skill in its own directory instead." >&2
    exit 2
  fi
  ;;
*) ;;
esac

exit 0
