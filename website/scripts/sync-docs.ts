/** A section of a source file published as a page of its own. */
interface Extract {
  /** Accepted `##` heading texts; the first one present is used. */
  headings: readonly string[];
  slug: string;
  title: string;
  lead?: string;
}

/** One source file and the page (or pages) it becomes. */
interface Source {
  file: string;
  slug: string;
  sidebarLabel?: string;
  sidebarOrder?: number;
  extracts?: readonly Extract[];
}

