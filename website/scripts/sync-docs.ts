/** Every ADR is a page under development/decisions, ordered by its number. */
function adrSources(): Source[] {
  return readdirSync(join(REPO, "docs/adr"))
    .filter((name) => /^\d{4}-.*\.md$/.test(name))
    .sort()
    .map((name) => ({
      file: `docs/adr/${name}`,
      slug: `development/decisions/${name.replace(/\.md$/, "")}`,
      sidebarOrder: Number(name.slice(0, 4)),
    }));
}

/** A heading's anchor as Starlight renders it (github-slugger rules). */
function slugify(text: string): string {
  return text
    .trim()
    .toLowerCase()
    .replace(/[`*_]/g, "")
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .replace(/\s/g, "-");
}

interface Page {
  slug: string;
  title: string;
  source: string;
  body: string[];
  sidebarLabel?: string;
  sidebarOrder?: number;
  lead?: string;
}

/** Splits one source into its pages, and records which page holds each anchor. */
function splitSource(source: Source, anchors: Map<string, Map<string, string>>): Page[] {
  const lines = readFileSync(join(REPO, source.file), "utf8").split("\n");
  const h1 = lines.findIndex((line) => line.startsWith("# "));
  if (h1 < 0) throw new Error(`${source.file}: no "# " heading to take the title from`);
  const main: Page = {
    slug: source.slug,
    title: (lines[h1] ?? "").slice(2).trim(),
    source: source.file,
    body: [],
    ...(source.sidebarLabel === undefined ? {} : { sidebarLabel: source.sidebarLabel }),
    ...(source.sidebarOrder === undefined ? {} : { sidebarOrder: source.sidebarOrder }),
  };
  const pages = [main];
  const found = new Set<Extract>();
  const fileAnchors = new Map<string, string>();
  anchors.set(source.file, fileAnchors);
  let current = main;
  let inFence = false;
  for (const line of lines.slice(h1 + 1)) {
    if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
    const heading = inFence ? null : /^(#{2,6})\s+(.*)$/.exec(line);
    if (heading?.[1] === "##") {
      const text = (heading[2] ?? "").trim();
      const extract = source.extracts?.find((e) => e.headings.includes(text));
      if (extract) {
        found.add(extract);
        current = {
          slug: extract.slug,
          title: extract.title,
          source: source.file,
          body: [],
          ...(extract.lead === undefined ? {} : { lead: extract.lead }),
        };
        pages.push(current);
        fileAnchors.set(slugify(text), current.slug);
        continue;
      }
      current = main;
    }
    if (heading) {
      fileAnchors.set(slugify(heading[2] ?? ""), current.slug);
      if (current !== main) {
        // An extracted section's subheadings move up one level on their own page.
        current.body.push(`${(heading[1] ?? "").slice(1)} ${heading[2]}`);
        continue;
      }
    }
    current.body.push(line);
  }
  for (const extract of source.extracts ?? []) {
    if (!found.has(extract)) {
      throw new Error(
        `${source.file}: no "## ${extract.headings.join('" or "## ')}" section for ${extract.slug}; update the map in website/scripts/sync-docs.ts`,
      );
    }
  }
  return pages;
}

/** Rewrites one link target from the source file's point of view. */
function rewriteTarget(
  target: string,
  page: Page,
  pageOf: (file: string, anchor: string) => string | undefined,
  problems: string[],
): string {
  if (/^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("/")) return target;
  const [path = "", fragment] = target.split("#", 2);
  const anchor = fragment === undefined ? "" : `#${fragment}`;
  const file =
    path === "" ? page.source : posix.normalize(posix.join(posix.dirname(page.source), path));
  const slug = pageOf(file, fragment ?? "");
  if (slug !== undefined) {
    return slug === page.slug && path === "" ? anchor : `/${slug}/${anchor}`;
  }
  const onDisk = join(REPO, file);
  if (file.startsWith("..") || !existsSync(onDisk)) {
    problems.push(`${page.source}: "${target}" resolves to nothing in the repository`);
    return target;
  }
  if (file.startsWith("docs/") && statSync(onDisk).isFile() && !file.endsWith(".md")) {
    const copy = join(ASSETS, file);
    mkdirSync(dirname(copy), { recursive: true });
    copyFileSync(onDisk, copy);
    return `/_repo/${file}${anchor}`;
  }
  const kind = statSync(onDisk).isDirectory() ? "tree" : "blob";
  return `${REPO_URL}/${kind}/main/${file.replace(/\/$/, "")}${anchor}`;
}

/** Rewrites every inline link and image outside code in a page body. */
function rewriteLinks(
  page: Page,
  pageOf: (file: string, anchor: string) => string | undefined,
  problems: string[],
): string {
  let inFence = false;
  return page.body
    .map((line) => {
      if (/^\s*(```|~~~)/.test(line)) inFence = !inFence;
      if (inFence) return line;
      return line
        .replace(/\]\(([^()\s]+)((?:\s+"[^"]*")?)\)/g, (_match, target: string, title: string) => {
          return `](${rewriteTarget(target, page, pageOf, problems)}${title})`;
        })
        .replace(
          /(<img\s[^>]*src=")([^"]+)(")/g,
          (_match, open: string, src: string, close: string) => {
            return `${open}${rewriteTarget(src, page, pageOf, problems)}${close}`;
          },
        );
    })
    .join("\n");
}

function frontmatter(page: Page): string {
  const lines = [
    "---",
    `title: ${JSON.stringify(page.title)}`,
    `editUrl: ${JSON.stringify(`${REPO_URL}/edit/main/${page.source}`)}`,
  ];
  if (page.sidebarLabel !== undefined || page.sidebarOrder !== undefined) {
    lines.push("sidebar:");
    if (page.sidebarLabel !== undefined)
      lines.push(`  label: ${JSON.stringify(page.sidebarLabel)}`);
    if (page.sidebarOrder !== undefined) lines.push(`  order: ${page.sidebarOrder}`);
  }
  lines.push("---", "");
  lines.push(`<!-- ${MARKER} from ${page.source}. Edit that file. -->`, "");
  return lines.join("\n");
}

/** Deletes every page an earlier run generated (found by its marker), so a dropped source leaves nothing behind. */
function removeGenerated(dir: string): void {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      removeGenerated(path);
    } else if (entry.name.endsWith(".md") && readFileSync(path, "utf8").includes(MARKER)) {
      rmSync(path);
    }
  }
}

function outputPath(slug: string): string {
  const isIndex = slug === "development/decisions";
  return join(CONTENT, isIndex ? `${slug}/index.md` : `${slug}.md`);
}

function main(): void {
  const sources = [...STATIC_SOURCES, ...adrSources()];
  const anchors = new Map<string, Map<string, string>>();
  const pages = sources.flatMap((source) => splitSource(source, anchors));
  const mainPage = new Map(sources.map((source) => [source.file, source.slug]));
  const pageOf = (file: string, anchor: string) =>
    anchors.get(file)?.get(anchor) ?? mainPage.get(file);

  removeGenerated(CONTENT);
  rmSync(ASSETS, { recursive: true, force: true });

  const problems: string[] = [];
  for (const page of pages) {
    const lead = page.lead === undefined ? "" : `${page.lead}\n\n`;
    const body = `${lead}${rewriteLinks(page, pageOf, problems).trim()}\n`;
    const out = outputPath(page.slug);
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, frontmatter(page) + body);
  }
  if (problems.length > 0) {
    throw new Error(`Unresolved links:\n  ${problems.join("\n  ")}`);
  }
  process.stdout.write(
    `sync-docs: ${pages.length} pages from ${sources.length} sources into ${relative(REPO, CONTENT)}\n`,
  );
}

main();
